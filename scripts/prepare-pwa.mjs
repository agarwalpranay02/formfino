import {readFile,writeFile} from 'node:fs/promises';
const offline=await readFile('public/offline.html','utf8');
// The browser stores the registered worker itself. Bundling this tiny public
// screen avoids Cache Storage failures and never persists the user's files.
await writeFile('public/sw.js',`/* Generated by scripts/prepare-pwa.mjs. No documents or application pages are cached. */
const OFFLINE_PAGE=${JSON.stringify(offline)};
self.addEventListener('fetch',event=>{
  if(event.request.method!=='GET'||event.request.mode!=='navigate'||new URL(event.request.url).origin!==self.location.origin)return;
  event.respondWith(fetch(event.request).catch(()=>new Response(OFFLINE_PAGE,{
    status:200,
    headers:{'Content-Type':'text/html; charset=utf-8','Cache-Control':'no-store','X-Content-Type-Options':'nosniff','Content-Security-Policy':"default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; frame-ancestors 'none'"}
  })));
});
`);
